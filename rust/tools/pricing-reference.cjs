// Optional reference-data regeneration; not needed by cargo test.
// Node 24+; supply a path to big.js 6.2.2 or install the root npm dependencies.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { stripTypeScriptTypes } = require('node:module');
const root = path.resolve(__dirname, '..', '..');
const modulePath = process.argv[2] || path.join(root, 'node_modules/big.js');
const Big = require(modulePath);
const packageInfo = require(path.join(path.dirname(require.resolve(modulePath)), 'package.json'));
if (packageInfo.version !== '6.2.2') throw new Error('Use big.js 6.2.2 for recorded fixtures');
if (Big.DP !== 20 || Big.RM !== 1) throw new Error('Unexpected big.js defaults');
const source = fs.readFileSync(path.join(root, 'src/services/quoter.service.ts'), 'utf8');
const { createHash } = require('node:crypto');
const blob = createHash('sha1').update('blob ' + Buffer.byteLength(source) + '\0').update(source).digest('hex');
if (blob !== 'f146a6eae43b7cc25f83bdba6322796da2fff07b') {
    throw new Error('The TypeScript pricing source differs from the pinned baseline');
}
// Run the actual standalone upstream functions, without loading application services.
const start = source.indexOf('export function getAmountOut(');
if (start < 0) throw new Error('Cannot locate upstream pricing functions');
const functions = stripTypeScriptTypes(source.slice(start)).replaceAll('export ', '');
const context = vm.createContext({ Big, Math });
vm.runInContext(functions, context);
const cases = [
    ['out', '10', '10000', '100000000', 30],
    ['out', '99600', '99900400', '10010', 30],
    ['in', '10', '100000000', '10000', 30],
    ['in', '100402', '9990', '100100402', 30],
    ['out', '1', '3', '10', 0],
    ['in', '2', '3', '10', 0],
    ['out', '10', '10', '100', 0],
    ['in', '50', '10', '100', 0],
    ['out', '1', '1000000', '1', 30],
    ['out', '100', '100', '100', 9999],
    ['in', '1', '100', '100', 9999],
    ['out', '1000000000000000000000000', '100000000000000000000000000', '200000000000000000000000000', 30],
    ['in', '1000000000000000000000000', '200000000000000000000000000', '100000000000000000000000000', 30],
    // Division is rounded to 20 decimal places by big.js before toFixed.
    ['out', '1000000000000000000000000000000', '1', '2', 0],
    ['in', '1', '1', '1000000000000000000000000000000', 0],
];
for (let i = 1; i <= 64; i++) {
    const ri = 1000 + i * 37;
    const ro = 10000 + i * 101;
    const amount = i * 7;
    cases.push([i % 2 ? 'out' : 'in', String(amount), String(ri), String(ro), [0, 30, 125, 9999][i % 4]]);
}
const lines = [
    '# Generated by tools/pricing-reference.cjs from the pinned TypeScript source.',
    '# big.js 6.2.2 defaults: DP=20, RM=1. Rust uses exact integer floor/ceiling.',
    '# direction\tamount\treserve_in\treserve_out\tfee_bps\ttypescript\texact_integer',
];
let differences = 0;
for (const [direction, amount, reserveIn, reserveOut, fee] of cases) {
    const fn = direction === 'out' ? context.getAmountOut : context.getAmountIn;
    const reference = fn(new Big(amount), new Big(reserveIn), new Big(reserveOut), fee / 100);
    const a = BigInt(amount), x = BigInt(reserveIn), y = BigInt(reserveOut);
    const multiplier = 10000n - BigInt(fee);
    const numerator = direction === 'out' ? a * multiplier * y : x * a * 10000n;
    const denominator = direction === 'out' ? x * 10000n + a * multiplier : (y - a) * multiplier;
    const exact = (direction === 'out' ? numerator / denominator : (numerator + denominator - 1n) / denominator).toString();
    if (reference !== exact) differences++;
    lines.push([direction, amount, reserveIn, reserveOut, fee, reference, exact].join('\t'));
}
if (differences !== 2) throw new Error('Expected exactly two documented precision differences');
const destination = path.join(root, 'rust/tests/fixtures/pricing.tsv');
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, lines.join('\n') + '\n');
console.log(`Wrote ${cases.length} cases: ${cases.length - differences} matches, ${differences} documented precision differences.`);
